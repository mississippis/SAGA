// Generate procedural simple checkerboard pattern
void generateCheckerboard(uint8_t* buffer, int width, int height, int checkSize) {
  for (int y = 0; y < height; y++) {
    for (int x = 0; x < width; x++) {
      bool isWhite = ((x / checkSize) % 2 == 0) != ((y / checkSize) % 2 == 0);
      buffer[y * width + x] = isWhite ? 0xFF : 0x00;
    }
  }
}

// Generate a horizontal gradient
void generateHorizontalGradient(uint8_t* buffer, int width, int height) {
  for (int y = 0; y < height; y++) {
    for (int x = 0; x < width; x++) {
      buffer[y * width + x] = (x * 255) / (width - 1);
    }
  }
}

// Generate a radial gradient
void generateRadialGradient(uint8_t* buffer, int width, int height) {
  int centerX = width / 2;
  int centerY = height / 2;
  float maxDist = sqrt(centerX * centerX + centerY * centerY);
  
  for (int y = 0; y < height; y++) {
    for (int x = 0; x < width; x++) {
      float distance = sqrt(pow(x - centerX, 2) + pow(y - centerY, 2));
      buffer[y * width + x] = 255 - min(255, (int)((distance * 255) / maxDist));
    }
  }
}

